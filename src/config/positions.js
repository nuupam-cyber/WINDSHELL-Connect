// =====================================================================
// src/config/positions.js — รายการตำแหน่งที่เลือกได้ของแต่ละ Role
// หน้า Admin แสดงเป็นตัวเลือก (dropdown) ตาม Role ของผู้ใช้ และ server ตรวจซ้ำว่าตำแหน่งตรงกับ Role
// เช่น Role technician เลือกได้เฉพาะตำแหน่งช่าง จะตั้งเป็น "หัวหน้าฝ่าย" ไม่ได้
//
// ชื่อตำแหน่งช่างมีคำสำคัญ (ไฟฟ้า ประปา แอร์ ลิฟต์ ประตู ...) ที่หน้าเว็บใช้จับคู่ช่างกับประเภทงาน
// ตอนหัวหน้าฝ่ายมอบหมายงาน (ROLE_FOR ใน public/app.js) ช่างที่ตำแหน่งตรงกับงานจะขึ้นก่อน
// ลูกบ้านไม่มีตำแหน่ง ส่วน Role ที่เพิ่มผ่านเว็บ (ไม่อยู่ในรายการนี้) ใช้ชื่อไทยของ Role (คำอธิบาย) เป็นตำแหน่งเดียวที่เลือกได้
// เช่น Role announcer คำอธิบาย "ผู้ประกาศข่าว" → เลือกตำแหน่งได้ "ผู้ประกาศข่าว"
// =====================================================================
const ROLE_POSITIONS = {
  admin: ['ผู้ดูแลระบบ'],
  dept_head: ['หัวหน้าฝ่ายช่างอาคาร', 'หัวหน้าฝ่ายนิติบุคคล'],
  technician: [
    'ช่างไฟฟ้า', 'ช่างประปา', 'ช่างแอร์', 'ช่างลิฟต์', 'ช่างประตูและกุญแจ', 'ช่างทั่วไป',
    'เจ้าหน้าที่ระบบดิจิทัล', 'เจ้าหน้าที่ความสะอาด', 'เจ้าหน้าที่รักษาความปลอดภัย', 'เจ้าหน้าที่ธุรการนิติบุคคล',
  ],
  resident: [],
};

// positionsFor('technician') → รายการตำแหน่งของ Role นั้น
// Role ที่เพิ่มผ่านเว็บ → [คำอธิบายของ Role] (ไม่มีคำอธิบายคืน [])
const positionsFor = (roleName, description) =>
  ROLE_POSITIONS[roleName] || (description ? [String(description).trim().slice(0, 100)] : []);

module.exports = { ROLE_POSITIONS, positionsFor };
